comment on column wurxbase.app_users.password is
  'Plaintext, copied as-is so their login keeps working for the length of one '
  'step. It is no more exposed here than it was in their project, where the '
  'key that could read it shipped in the page source. Delete this column once '
  'the session comes from our own auth.';

