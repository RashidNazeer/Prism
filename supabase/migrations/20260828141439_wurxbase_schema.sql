create index brand_monthly_budgets_brand_month_idx
  on wurxbase.brand_monthly_budgets (brand, month);

create index audit_logs_created_at_idx    on wurxbase.audit_logs (created_at desc);
create index join_requests_status_idx     on wurxbase.join_requests (status);

-- ------------------------------------------------------------ row security --
--
-- Deny by default on every table, then one policy set. Paid Collabs lives at
-- /admin/collabs, which our router guards with allow={['ops','admin']} — the
-- same pair `public.is_staff()` already answers for. So staff get full use and
-- nobody else gets anything, which is a strict improvement on the old project
-- where an anon key in the page source could read and write all of it.
--
-- DELETE IS GRANTED TO STAFF FOR NOW, and it should not stay that way. Their
-- saves delete as a matter of course — insert the new row, sweep the old ones
-- — so narrowing delete today would break saving for ops. Once the write paths
-- stop deleting (PARKED 34), delete should drop to admin only.

alter table wurxbase.creators              enable row level security;
alter table wurxbase.activity_logs         enable row level security;
alter table wurxbase.app_users             enable row level security;
alter table wurxbase.app_settings          enable row level security;
alter table wurxbase.join_requests         enable row level security;
alter table wurxbase.brand_monthly_budgets enable row level security;
alter table wurxbase.revoked_sessions      enable row level security;
alter table wurxbase.audit_logs            enable row level security;

do $$
declare t text;
begin
  foreach t in array array[
    'creators', 'activity_logs', 'app_users', 'app_settings',
    'join_requests', 'brand_monthly_budgets', 'revoked_sessions', 'audit_logs'
  ]
  loop
    execute format(
      'create policy %I on wurxbase.%I for select to authenticated using (public.is_staff())',
      t || '_select_staff', t);
    execute format(
      'create policy %I on wurxbase.%I for insert to authenticated with check (public.is_staff())',
      t || '_insert_staff', t);
    execute format(
      'create policy %I on wurxbase.%I for update to authenticated using (public.is_staff()) with check (public.is_staff())',
      t || '_update_staff', t);
    execute format(
      'create policy %I on wurxbase.%I for delete to authenticated using (public.is_staff())',
      t || '_delete_staff', t);
  end loop;
end $$;

-- ------------------------------------------------------------------ grants --
--
-- `Automatically expose new tables` is OFF on this project, which also switches
-- off the default grants to service_role. Every table needs both halves spelled
-- out or the Edge Functions that touch them see an empty database and say
-- nothing about it.

do $$
declare t text;
begin
  foreach t in array array[
    'creators', 'activity_logs', 'app_users', 'app_settings',
    'join_requests', 'brand_monthly_budgets', 'revoked_sessions', 'audit_logs'
  ]
  loop
    execute format('grant select, insert, update, delete on table wurxbase.%I to authenticated', t);
    execute format('grant all privileges on table wurxbase.%I to service_role', t);
  end loop;
end $$;

-- Identity columns need their sequence, or an insert fails with a permission
-- error that names the sequence rather than the table and reads like a bug.
grant usage, select on all sequences in schema wurxbase to authenticated, service_role;

-- anon gets nothing. Paid Collabs is behind a login and always will be.
revoke all on all tables in schema wurxbase from anon;
