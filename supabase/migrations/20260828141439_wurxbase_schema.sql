-- ===========================================================================
-- WurxBase comes home.
--
-- Paid Collabs has been talking to a SEPARATE Supabase project
-- (bnevtdezskftlrjjgbsg) straight from the browser, with a publishable key
-- that ships in our bundle and no authentication of any kind. Rashid has
-- decided there is now one copy of that app and it is ours, so its data moves
-- here and is governed like everything else we own.
--
-- ITS OWN SCHEMA, NOT `public`, and that is the whole trick. Their code says
-- `.from('creators')` in forty-two places and `.from('app_users')` in
-- twenty-four; putting these tables in `public` would either collide with our
-- own names one day or force a rewrite of every call site. A schema means the
-- client is configured once — `{ db: { schema: 'wurxbase' } }` — and not one
-- line of their code changes.
--
-- THEIR `creators` IS NOT OUR CREATORS, and the two must never be merged on a
-- hunch. Theirs is a paid-deal tracker: a brand, a deal string like
-- "$200 for 6", who hired them, and an array of delivered video codes. Ours is
-- a person with a login, an application and a brand hub. Same word, different
-- grain. Anything that wants to join them has to do it deliberately, on
-- TikTok handle or video id, in a view written for the purpose.
--
-- FAITHFUL COPY, WITH ONE DELIBERATE CHANGE. Types are exactly what their
-- database reports — probed column by column against the live project, because
-- their PostgREST refuses the OpenAPI spec to anon and a sample row cannot tell
-- text from date or integer from numeric. The one change: `json` becomes
-- `jsonb`. Every value in those columns is machine-written objects and arrays,
-- so nothing observable changes, and jsonb is what lets us index and constrain
-- these columns later. That "later" is the point of the whole move.
--
-- WHAT THIS MIGRATION DELIBERATELY DOES NOT DO
--
--   * No unique constraint on (action, target) yet. It is the thing that would
--     make the angle-test and contract overwrite bugs IMPOSSIBLE rather than
--     merely unlikely — see PARKED 34 — but their save inserts a new row and
--     then deletes the old ones, so adding it now breaks every save on the day
--     it lands. The constraint arrives with the code change, not before it.
--   * `app_users.password` is copied as it is: PLAINTEXT, and readable by any
--     signed-in staff member. That is exactly as exposed as it is today and no
--     worse, because their login screen still reads it to check a password in
--     the browser. It stops being true in the very next step, when the session
--     comes from our own auth and their login is bypassed entirely. Revoking
--     the column before then would lock the team out of Paid Collabs.
-- ===========================================================================

create schema if not exists wurxbase;

comment on schema wurxbase is
  'WurxBase (Paid Collabs), vendored in from its own Supabase project on '
  '2026-08-28. Kept out of public so their `.from(...)` calls need no rewrite '
  'and can never collide with ours.';

-- PostgREST reaches this schema only once it is added to the exposed list in
-- the project API settings. Usage alone is not enough, but it is required.
grant usage on schema wurxbase to authenticated, service_role;

-- ------------------------------------------------------------------ tables --

-- The paid-deal tracker. 1,249 rows at the time of the move.
create table wurxbase.creators (
  id                bigint generated by default as identity primary key,
  airtable_id       text,                       -- provenance: rows began in Airtable
  created_time      timestamptz,                -- when Airtable first saw it
  inserted_at       timestamptz default now(),  -- when this row was written here
  brand             text,
  name              text,
  whatsapp_number   text,
  deal              text,                       -- free text, e.g. "$200 for 6"
  payment_status    text,
  tiktok_account    text,
  tiktok_account_2  text,
  videos            text,                       -- a status word, not a count
  hiring_date       text,                       -- text in their schema, not date
  deadline          date,                       -- and this one genuinely is a date
  hired_by          text,
  paypal            text,
  zelle             text,
  email             text,
  product           text,
  comments          text,
  category          text,
  status            text,                       -- approved / pending / rejected
  gmv               numeric,
  ad_spent          numeric,
  total_gmv         numeric,
  video_codes       jsonb,                      -- [{video, adCode, auth, ...}]
  monthly           jsonb,                      -- {euka: {at, l30, tier}}
  products          jsonb
);

comment on column wurxbase.creators.hiring_date is
  'Text, not a date, in the source schema. Their code slices it as a string '
  '(`String(c.hiring_date).slice(0,7)`), so converting it to `date` here would '
  'change what that produces. Left as text on purpose.';

comment on column wurxbase.creators.video_codes is
  'The delivered videos for this deal. Joined to our ad figures on the TikTok '
  'video id — see src/routes/admin/collab-ad-math.ts. Rebuilt wholesale by '
  'several of their write paths, which is PARKED 34.';

